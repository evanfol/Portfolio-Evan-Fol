def construire_liste_ppn_complete(df_wikidata):

    # 1. Récupération des PPN GEN_AUT
    df_ppn = recuperer_ppn_gen_aut()

    # 2. Enrichissement Wikidata
    df_gen_aut = completer_avec_wikidata(df_ppn)

    # 3. Ajout de la raison
    df_gen_aut = df_gen_aut.copy()
    df_gen_aut["Raisons"] = "GEN_AUT"

    # 4. Fusion avec les PPN trouvés par Wikidata
    df_global = pd.concat(
        [df_wikidata, df_gen_aut],
        ignore_index=True
    )

    # 5. Nettoyage PPN
    df_global["ppn"] = (
        df_global["ppn"]
        .astype(str)
        .str.strip()
    )

    # 6. Suppression doublons
    df_global = (
        df_global
        .drop_duplicates(subset=["ppn"])
        .reset_index(drop=True)
    )

    # 7. Retrait Rousseau / Calvin
    ppn_a_retirer = {
        "028202368",
        "026763362"
    }

    df_global = (
        df_global[
            ~df_global["ppn"].isin(ppn_a_retirer)
        ]
        .reset_index(drop=True)
    )

    print(
        f"Liste finale : {len(df_global):,} PPN uniques"
    )

    return df_global