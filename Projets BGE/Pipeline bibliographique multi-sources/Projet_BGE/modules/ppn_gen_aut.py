# COMPLÉTER LE DATAFRAME
# ============================================================

def completer_avec_wikidata(df):

    df = df.copy()

    # --------------------------------------------------------
    # PPN TOUJOURS EN TEXTE
    # --------------------------------------------------------

    df["ppn"] = (
        df["ppn"]
        .astype(str)
        .str.strip()
    )

    # --------------------------------------------------------
    # Colonnes attendues
    # --------------------------------------------------------

    colonnes = [
        "NomComplet",
        "Occupations",
        "Raisons",
        "bnf_id",
        "gnd_id"
    ]

    for col in colonnes:

        if col not in df.columns:
            df[col] = None

    # --------------------------------------------------------
    # Récupération Wikidata
    # --------------------------------------------------------

    df_wikidata = recuperer_wikidata(df)

    if df_wikidata.empty:

        print("\nAucune correspondance Wikidata trouvée.")

        return df

    # --------------------------------------------------------
    # Fusion
    # --------------------------------------------------------

    df = df.merge(
        df_wikidata,
        on="ppn",
        how="left"
    )

    # --------------------------------------------------------
    # Fonction permettant de reconnaître None / NaN / ""
    # --------------------------------------------------------

    def est_vide(serie):

        return (
            serie.isna()
            | serie.astype(str).str.strip().isin(
                ["", "None", "nan", "<NA>"]
            )
        )

    # --------------------------------------------------------
    # Compléter uniquement les champs manquants
    # --------------------------------------------------------

    correspondances = {

        "NomComplet":
            "NomComplet_wikidata",

        "Occupations":
            "Occupations_wikidata",

        "bnf_id":
            "bnf_id_wikidata",

        "gnd_id":
            "gnd_id_wikidata"
    }

    for colonne, colonne_wikidata in correspondances.items():

        masque = est_vide(df[colonne])

        df.loc[masque, colonne] = (
            df.loc[masque, colonne_wikidata]
        )

    # --------------------------------------------------------
    # Suppression colonnes temporaires
    # --------------------------------------------------------

    colonnes_wikidata = [
        c
        for c in df.columns
        if c.endswith("_wikidata")
    ]

    df = df.drop(
        columns=colonnes_wikidata
    )

    # --------------------------------------------------------
    # Remettre ordre original des colonnes
    # --------------------------------------------------------

    return df

def recuperer_ppn_gen_aut(rows=10000):

    url = "https://www.idref.fr/Sru/Solr"

    params = {
        "q": "classification_t:GEN_AUT",
        "sort": "score desc",
        "version": "2.2",
        "start": 0,
        "rows": rows,
        "fl": "ppn_z,persname_t",
        "wt": "json"
    }

    response = requests.get(
        url,
        params=params,
        timeout=60
    )

    response.raise_for_status()

    data = response.json()

    lignes = []

    for doc in data["response"]["docs"]:

        ppn = doc.get("ppn_z")
        nom_prenom = doc.get("persname_t")

        if isinstance(ppn, list):
            ppn = ppn[0] if ppn else None

        if isinstance(nom_prenom, list):
            nom_prenom = (
                nom_prenom[0]
                if nom_prenom
                else None
            )

        lignes.append({
            "ppn": ppn,
            "NomComplet": nom_prenom
        })

    df = pd.DataFrame(lignes)

    df = (
        df
        .dropna(subset=["ppn"])
        .drop_duplicates(subset=["ppn"])
        .reset_index(drop=True)
    )

    df["ppn"] = df["ppn"].astype(str)

    return df

