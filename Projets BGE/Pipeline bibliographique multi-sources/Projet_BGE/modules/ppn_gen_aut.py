import pandas as pd
import requests
import time
from requests.adapters import HTTPAdapter
from urllib3.util.retry import Retry


# ============================================================
# CONFIGURATION
# ============================================================

WIKIDATA_URL = "https://query.wikidata.org/sparql"

BATCH_SIZE = 150


# ============================================================
# SESSION HTTP OPTIMISÉE
# ============================================================

def creer_session():

    session = requests.Session()

    retry = Retry(
        total=5,
        connect=5,
        read=5,
        status=5,
        backoff_factor=1,
        status_forcelist=[429, 500, 502, 503, 504],
        allowed_methods=["GET", "POST"]
    )

    adapter = HTTPAdapter(
        max_retries=retry,
        pool_connections=10,
        pool_maxsize=10
    )

    session.mount("https://", adapter)

    session.headers.update({
        "User-Agent": "Geneve-Bibliographic-Research/1.0",
        "Accept": "application/sparql-results+json"
    })

    return session


# ============================================================
# REQUÊTE WIKIDATA PAR LOT DE PPN
# ============================================================

def requete_wikidata_ppn(ppns, session):

    valeurs = " ".join(
        f'"{str(ppn).strip()}"'
        for ppn in ppns
    )

    query = f"""
    SELECT
        ?ppn
        (SAMPLE(?nom) AS ?NomComplet)
        (GROUP_CONCAT(DISTINCT ?occupationLabel; separator=" | ") AS ?Occupations)
        (SAMPLE(?bnf) AS ?bnf_id)
        (SAMPLE(?gnd) AS ?gnd_id)

    WHERE {{

        VALUES ?ppn {{
            {valeurs}
        }}

        ?personne wdt:P269 ?ppn .

        OPTIONAL {{
            ?personne rdfs:label ?nom .
            FILTER(LANG(?nom) = "fr")
        }}

        OPTIONAL {{
            ?personne wdt:P106 ?occupation .

            ?occupation rdfs:label ?occupationLabel .

            FILTER(LANG(?occupationLabel) = "fr")
        }}

        OPTIONAL {{
            ?personne wdt:P268 ?bnf .
        }}

        OPTIONAL {{
            ?personne wdt:P227 ?gnd .
        }}
    }}

    GROUP BY ?ppn
    """

    response = session.get(
        WIKIDATA_URL,
        params={
            "query": query,
            "format": "json"
        },
        timeout=60
    )

    response.raise_for_status()

    data = response.json()

    lignes = []

    for x in data["results"]["bindings"]:

        lignes.append({

            "ppn": x["ppn"]["value"],

            "NomComplet_wikidata":
                x.get("NomComplet", {}).get("value"),

            "Occupations_wikidata":
                x.get("Occupations", {}).get("value"),

            "bnf_id_wikidata":
                x.get("bnf_id", {}).get("value"),

            "gnd_id_wikidata":
                x.get("gnd_id", {}).get("value")
        })

    return lignes


# ============================================================
# RÉCUPÉRER WIKIDATA POUR TOUS LES PPN
# ============================================================

def recuperer_wikidata(df, batch_size=BATCH_SIZE):

    session = creer_session()

    # --------------------------------------------------------
    # Sécurisation des PPN
    # --------------------------------------------------------

    ppns = (
        df["ppn"]
        .dropna()
        .astype(str)
        .str.strip()
        .drop_duplicates()
        .tolist()
    )

    resultats = []

    total = len(ppns)

    print(f"{total:,} PPN à rechercher sur Wikidata\n")

    # --------------------------------------------------------
    # Traitement par lots
    # --------------------------------------------------------

    for debut in range(0, total, batch_size):

        lot = ppns[debut:debut + batch_size]

        try:

            lignes = requete_wikidata_ppn(
                lot,
                session
            )

            resultats.extend(lignes)

            print(
                f"✓ {min(debut + batch_size, total):,}/{total:,}"
                f" — {len(lignes)} correspondances"
            )

        except Exception as e:

            print(
                f"✗ Lot {debut:,}-{debut + len(lot):,} : {e}"
            )

        # Petit délai pour respecter WDQS
        time.sleep(0.2)

    return pd.DataFrame(resultats)


