thread_local = threading.local()


def creer_session(
    pool_size
):

    session = requests.Session()

    retry = Retry(

        total=MAX_RETRIES,

        connect=MAX_RETRIES,

        read=MAX_RETRIES,

        status=MAX_RETRIES,

        backoff_factor=0.5,

        status_forcelist=[
            429,
            500,
            502,
            503,
            504
        ],

        allowed_methods=[
            "GET",
            "POST"
        ],

        raise_on_status=False
    )

    adapter = HTTPAdapter(

        max_retries=retry,

        pool_connections=
            pool_size + 4,

        pool_maxsize=
            pool_size + 4
    )

    session.mount(
        "https://",
        adapter
    )

    session.headers.update({

        "User-Agent":
            "BGE-SUDOC-Optimisation-Finale/1.0",

        "Accept-Encoding":
            "gzip, deflate"
    })

    return session


def obtenir_session(
    pool_size
):

    cle = (
        f"session_{pool_size}"
    )

    if not hasattr(
        thread_local,
        cle
    ):

        setattr(
            thread_local,
            cle,
            creer_session(
                pool_size
            )
        )

    return getattr(
        thread_local,
        cle
    )


