def nom_local(
    tag
):

    return tag.rsplit(
        "}",
        1
    )[-1]


def datafields(
    record,
    tag
):

    return [

        element

        for element
        in record.iter()

        if (
            nom_local(
                element.tag
            )
            == "datafield"

            and element.attrib.get(
                "tag"
            )
            == tag
        )
    ]


def controlfield(
    record,
    tag
):

    for element in record.iter():

        if (
            nom_local(
                element.tag
            )
            == "controlfield"

            and element.attrib.get(
                "tag"
            )
            == tag

            and element.text
        ):

            return (
                element.text
                .strip()
            )

    return None


def sous_champs(
    champ,
    code
):

    if champ is None:
        return []

    resultats = []

    for element in champ:

        if (
            nom_local(
                element.tag
            )
            == "subfield"

            and element.attrib.get(
                "code"
            )
            == code

            and element.text
        ):

            valeur = (
                element.text
                .strip()
            )

            if valeur:

                resultats.append(
                    valeur
                )

    return resultats


def sous_champ(
    champ,
    code
):

    valeurs = sous_champs(
        champ,
        code
    )

    return (
        valeurs[0]
        if valeurs
        else None
    )


def extraire_records(
    xml_bytes
):

    root = ET.fromstring(
        xml_bytes
    )

    records = []

    for element in root.iter():

        if (
            nom_local(
                element.tag
            )
            != "recordData"
        ):

            continue

        for enfant in element:

            if (
                nom_local(
                    enfant.tag
                )
                == "record"
            ):

                records.append(
                    enfant
                )

                break

    return records


