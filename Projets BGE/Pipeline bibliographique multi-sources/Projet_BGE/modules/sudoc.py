def traiter_lot_unimarc(
    lot
):

    resultats = {}

    erreurs = []

    try:

        reponses = (
            requete_sru_robuste(
                lot,
                "unimarc",
                UNIMARC_WORKERS
            )
        )

        for xml_bytes in reponses:

            records = (
                extraire_records(
                    xml_bytes
                )
            )

            for record in records:

                notice = (
                    parser_unimarc(
                        record
                    )
                )

                if not notice:
                    continue

                resultats[
                    notice[
                        "ppn"
                    ]
                ] = notice

    except Exception:

        erreurs.extend(
            lot
        )

    return (
        resultats,
        erreurs
    )


