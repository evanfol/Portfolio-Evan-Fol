PPN_RE = re.compile(
    r"[^0-9X]"
)


def normaliser_ppn(
    valeur
):

    if pd.isna(
        valeur
    ):
        return None

    ppn = (
        str(valeur)
        .strip()
        .upper()
    )

    if ppn.endswith(
        ".0"
    ):

        ppn = ppn[:-2]

    ppn = PPN_RE.sub(
        "",
        ppn
    )

    if not ppn:
        return None

    if (
        ppn.isdigit()
        and len(ppn) < 9
    ):

        ppn = ppn.zfill(
            9
        )

    if not re.fullmatch(
        r"[0-9]{8}[0-9X]",
        ppn
    ):

        return None

    return ppn


