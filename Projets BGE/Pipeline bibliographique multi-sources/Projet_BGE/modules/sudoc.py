def requete_sparql_lot(
    liste_ppn
):

    values = "\n".join(

        f'("{ppn}" '
        f'<http://www.idref.fr/{ppn}/id>)'

        for ppn
        in liste_ppn
    )

    query = f"""
SELECT DISTINCT
    ?ppn
    ?document

WHERE {{

    VALUES (?ppn ?idref) {{

        {values}

    }}

    ?document
        ?role
        ?idref .

    FILTER(

        STRSTARTS(
            STR(?document),
            "http://www.sudoc.fr/"
        )

    )

}}
"""

    session = obtenir_session(
        SPARQL_WORKERS
    )

    response = session.post(

        SPARQL_URL,

        data={
            "query":
                query,

            "format":
                "json"
        },

        headers={
            "Accept":
                "application/sparql-results+json"
        },

        timeout=(
            CONNECT_TIMEOUT,
            READ_TIMEOUT
        )
    )

    response.raise_for_status()

    bindings = (
        response
        .json()
        ["results"]
        ["bindings"]
    )

    mapping = []

    for ligne in bindings:

        try:

            ppn_idref = (
                ligne[
                    "ppn"
                ][
                    "value"
                ]
            )

            uri = (
                ligne[
                    "document"
                ][
                    "value"
                ]
            )

        except KeyError:

            continue

        match = (
            PPN_SUDOC_URI_RE
            .search(
                uri
            )
        )

        if not match:
            continue

        mapping.append(
            (
                ppn_idref,
                match
                .group(1)
                .upper()
            )
        )

    return mapping


