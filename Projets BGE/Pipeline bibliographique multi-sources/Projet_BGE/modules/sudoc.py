def nettoyer_texte(
    texte
):

    if not texte:
        return None

    texte = (
        str(texte)
        .strip()
    )

    texte = re.sub(
        r"\s*[/:;,]\s*$",
        "",
        texte
    )

    return (
        texte
        or None
    )


ANNEE_RE = re.compile(
    r"\b(1[0-9]{3}|20[0-9]{2}|21[0-9]{2})\b"
)


def extraire_annee(
    valeurs
):

    for valeur in valeurs:

        if not valeur:
            continue

        match = (
            ANNEE_RE.search(
                str(
                    valeur
                )
            )
        )

        if match:

            return int(
                match.group(1)
            )

    return None


def parser_unimarc(
    record
):

    ppn = normaliser_ppn(

        controlfield(
            record,
            "001"
        )
    )

    if not ppn:
        return None

    # ========================================================
    # ISBN
    # ========================================================

    isbns = []

    for champ in datafields(
        record,
        "010"
    ):

        for valeur in sous_champs(
            champ,
            "a"
        ):

            isbn = normaliser_isbn(
                valeur
            )

            if isbn:

                isbns.append(
                    isbn
                )

    isbns = list(
        dict.fromkeys(
            isbns
        )
    )

    # Pas d'ISBN :
    # on ne parse pas le reste.
    if not isbns:

        return {
            "ppn":
                ppn,

            "isbns":
                []
        }

    # ========================================================
    # TITRE
    # ========================================================

    champs200 = datafields(
        record,
        "200"
    )

    champ200 = (
        champs200[0]
        if champs200
        else None
    )

    titres = [

        texte

        for valeur
        in sous_champs(
            champ200,
            "a"
        )

        if (
            texte :=
            nettoyer_texte(
                valeur
            )
        )
    ]

    sous_titres = [

        texte

        for valeur
        in sous_champs(
            champ200,
            "e"
        )

        if (
            texte :=
            nettoyer_texte(
                valeur
            )
        )
    ]

    titres = list(
        dict.fromkeys(
            titres
        )
    )

    sous_titres = list(
        dict.fromkeys(
            sous_titres
        )
    )

    titre = (
        " ; ".join(
            titres
        )
        if titres
        else None
    )

    sous_titre = (
        " ; ".join(
            sous_titres
        )
        if sous_titres
        else None
    )

    if (
        titre
        and sous_titre
    ):

        titre = (
            f"{titre} : "
            f"{sous_titre}"
        )

    elif not titre:

        titre = (
            sous_titre
        )

    # ========================================================
    # AUTEUR
    # ========================================================

    auteur = None

    champs_auteur = (
        datafields(
            record,
            "700"
        )
    )

    if not champs_auteur:

        champs_auteur = (
            datafields(
                record,
                "701"
            )
        )

    if champs_auteur:

        champ = (
            champs_auteur[0]
        )

        nom = nettoyer_texte(

            sous_champ(
                champ,
                "a"
            )
        )

        prenom = nettoyer_texte(

            sous_champ(
                champ,
                "b"
            )
        )

        if (
            nom
            and prenom
        ):

            auteur = (
                f"{nom}, {prenom}"
            )

        else:

            auteur = (
                nom
                or prenom
            )

    # ========================================================
    # PUBLICATION
    # ========================================================

    publication = (
        datafields(
            record,
            "214"
        )
    )

    if not publication:

        publication = (
            datafields(
                record,
                "210"
            )
        )

    lieux = []
    editeurs = []
    annees = []

    for champ in publication:

        lieux.extend(
            sous_champs(
                champ,
                "a"
            )
        )

        editeurs.extend(
            sous_champs(
                champ,
                "c"
            )
        )

        annees.extend(
            sous_champs(
                champ,
                "d"
            )
        )

    lieux = [

        texte

        for valeur
        in lieux

        if (
            texte :=
            nettoyer_texte(
                valeur
            )
        )
    ]

    editeurs = [

        texte

        for valeur
        in editeurs

        if (
            texte :=
            nettoyer_texte(
                valeur
            )
        )
    ]

    lieux = list(
        dict.fromkeys(
            lieux
        )
    )

    editeurs = list(
        dict.fromkeys(
            editeurs
        )
    )

    lieu = (
        " - ".join(
            lieux
        )
        if lieux
        else None
    )

    editeur = (
        " - ".join(
            editeurs
        )
        if editeurs
        else None
    )

    annee = (
        extraire_annee(
            annees
        )
    )

    return {

        "ppn":
            ppn,

        "isbns":
            isbns,

        "titre":
            titre,

        "annee":
            annee,

        "nomAuteur":
            auteur,

        "lieuPublication":
            lieu,

        "editeur":
            editeur
    }


