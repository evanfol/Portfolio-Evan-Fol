ISBN10_RE = re.compile(
    r"\d{9}[\dX]"
)

ISBN13_RE = re.compile(
    r"\d{13}"
)

ISBN_DEBUT_RE = re.compile(
    r"^\s*([0-9X][0-9X\-\s]{8,30})"
)

ISBN_NETTOYAGE_RE = re.compile(
    r"[^0-9X]"
)


def isbn10_valide(
    isbn
):

    if not ISBN10_RE.fullmatch(
        isbn
    ):
        return False

    total = 0

    for i, c in enumerate(
        isbn
    ):

        valeur = (
            10
            if c == "X"
            else int(c)
        )

        total += (
            (10 - i)
            * valeur
        )

    return (
        total % 11
        == 0
    )


def isbn13_valide(
    isbn
):

    if not ISBN13_RE.fullmatch(
        isbn
    ):
        return False

    somme = 0

    for i, c in enumerate(
        isbn[:12]
    ):

        n = int(c)

        somme += (
            n
            if i % 2 == 0
            else n * 3
        )

    cle = (
        10
        - somme % 10
    ) % 10

    return (
        cle
        == int(
            isbn[-1]
        )
    )


def isbn10_vers_13(
    isbn10
):

    base = (
        "978"
        + isbn10[:9]
    )

    somme = 0

    for i, c in enumerate(
        base
    ):

        n = int(c)

        somme += (
            n
            if i % 2 == 0
            else n * 3
        )

    cle = (
        10
        - somme % 10
    ) % 10

    return (
        base
        + str(cle)
    )


def normaliser_isbn(
    valeur
):

    if not valeur:
        return None

    texte = (
        str(valeur)
        .upper()
        .strip()
    )

    match = (
        ISBN_DEBUT_RE
        .match(
            texte
        )
    )

    if match:

        texte = (
            match.group(1)
        )

    isbn = (
        ISBN_NETTOYAGE_RE
        .sub(
            "",
            texte
        )
    )

    if len(isbn) == 13:

        if isbn13_valide(
            isbn
        ):

            return isbn

        return None

    if len(isbn) == 10:

        if not isbn10_valide(
            isbn
        ):

            return None

        isbn13 = (
            isbn10_vers_13(
                isbn
            )
        )

        if isbn13_valide(
            isbn13
        ):

            return isbn13

    return None


