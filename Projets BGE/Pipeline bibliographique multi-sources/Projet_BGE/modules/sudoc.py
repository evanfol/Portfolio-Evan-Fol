# ÉTAPE 3
#
# PICA CIBLÉ
# ============================================================

def recuperer_ceb_cible(
    liste_ppn
):

    lots = [

        liste_ppn[
            i:
            i + PICA_BATCH_SIZE
        ]

        for i in range(
            0,
            len(
                liste_ppn
            ),
            PICA_BATCH_SIZE
        )
    ]

    analyses = {}

    erreurs = []

    debut = (
        time.perf_counter()
    )

    print()
    print("=" * 100)
    print("3/4 — PICA CIBLÉ 012V$c = ceb")
    print("=" * 100)

    print(
        f"PPN avec ISBN    : "
        f"{len(liste_ppn):,}"
    )

    print(
        f"Batch            : "
        f"{PICA_BATCH_SIZE}"
    )

    print(
        f"Workers          : "
        f"{PICA_WORKERS}"
    )

    print(
        f"Lots             : "
        f"{len(lots):,}"
    )

    with ThreadPoolExecutor(
        max_workers=
            PICA_WORKERS
    ) as executor:

        futures = {

            executor.submit(
                traiter_lot_pica,
                lot
            ):
            lot

            for lot in lots
        }

        termines = 0

        for future in as_completed(
            futures
        ):

            termines += 1

            try:

                analyses_lot, erreurs_lot = (
                    future.result()
                )

                analyses.update(
                    analyses_lot
                )

                erreurs.extend(
                    erreurs_lot
                )

            except Exception:

                erreurs.extend(
                    futures[
                        future
                    ]
                )

            if (
                termines % 25 == 0
                or termines == len(
                    lots
                )
            ):

                print(
                    f"{termines:>4}/"
                    f"{len(lots)} lots "
                    f"| analysés={len(analyses):,} "
                    f"| erreurs={len(erreurs):,}",
                    end="\r"
                )

    duree = (
        time.perf_counter()
        - debut
    )

    demandes = set(
        liste_ppn
    )

    recus = set(
        analyses
    )

    manquants = (
        demandes
        - recus
    )

    ppn_ceb = {

        ppn

        for ppn, ceb
        in analyses.items()

        if ceb
    }

    print()
    print()

    print(
        f"Durée PICA       : "
        f"{duree:.3f} s"
    )

    print(
        f"PPN analysés     : "
        f"{len(analyses):,}"
    )

    print(
        f"CEB              : "
        f"{len(ppn_ceb):,}"
    )

    print(
        f"PPN PICA absents : "
        f"{len(manquants):,}"
    )

    print(
        f"Erreurs          : "
        f"{len(erreurs):,}"
    )

    return (
        ppn_ceb,
        manquants,
        erreurs,
        duree
    )


