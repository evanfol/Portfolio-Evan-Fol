# ÉTAPE 4
#
# CONSTRUCTION DU RÉSULTAT FINAL
# ============================================================

def construire_resultat_final(
    mapping,
    notices,
    ppn_ceb
):

    debut = (
        time.perf_counter()
    )

    lignes = []

    append = (
        lignes.append
    )

    for (
        ppn_idref,
        ppn_sudoc
    ) in mapping:

        # ----------------------------------------------------
        # EXCLUSION CEB
        # ----------------------------------------------------

        if ppn_sudoc in ppn_ceb:
            continue

        notice = notices.get(
            ppn_sudoc
        )

        if not notice:
            continue

        isbns = notice.get(
            "isbns"
        )

        if not isbns:
            continue

        for isbn in isbns:

            append({

                "ppn":
                    ppn_idref,

                "ppn_sudoc":
                    ppn_sudoc,

                "isbn":
                    isbn,

                "titre":
                    notice.get(
                        "titre"
                    ),

                "annee":
                    notice.get(
                        "annee"
                    ),

                "nomAuteur":
                    notice.get(
                        "nomAuteur"
                    ),

                "lieuPublication":
                    notice.get(
                        "lieuPublication"
                    ),

                "editeur":
                    notice.get(
                        "editeur"
                    )
            })

    df = pd.DataFrame.from_records(
        lignes
    )

    if not df.empty:

        df.drop_duplicates(

            subset=[
                "ppn",
                "isbn"
            ],

            keep="first",

            inplace=True
        )

        df[
            "ppn"
        ] = (
            df[
                "ppn"
            ]
            .astype(
                "string"
            )
        )

        df[
            "ppn_sudoc"
        ] = (
            df[
                "ppn_sudoc"
            ]
            .astype(
                "string"
            )
        )

        df[
            "isbn"
        ] = (
            df[
                "isbn"
            ]
            .astype(
                "string"
            )
        )

        df[
            "annee"
        ] = (
            pd.to_numeric(
                df[
                    "annee"
                ],
                errors="coerce"
            )
            .astype(
                "Int64"
            )
        )

        df.reset_index(
            drop=True,
            inplace=True
        )

    duree = (
        time.perf_counter()
        - debut
    )

    return (
        df,
        duree
    )


